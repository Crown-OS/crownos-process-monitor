//! DNS servers from systemd-resolved, or `/etc/resolv.conf` without it.

use std::net::{IpAddr, Ipv4Addr, Ipv6Addr};
use std::sync::Arc;

use zbus::{Connection, Variant};

use crate::util::dbus;

const RESOLVED: &str = "org.freedesktop.resolve1";
const RESOLVED_PATH: &str = "/org/freedesktop/resolve1";
const RESOLVED_MANAGER: &str = "org.freedesktop.resolve1.Manager";
const FAMILY_INET: i32 = 2;
const FAMILY_INET6: i32 = 10;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum DnsSource {
    Resolved,
    ResolvConf,
    #[default]
    Unknown,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct DnsServers {
    pub servers: Arc<[IpAddr]>,
    pub source: DnsSource,
}

/// `nameserver` lines; zone suffixes (`fe80::1%wlo1`) are dropped.
pub(crate) fn parse_resolv_conf(text: &str) -> Vec<IpAddr> {
    text.lines()
        .filter_map(|line| line.trim().strip_prefix("nameserver"))
        .filter_map(|rest| {
            let address = rest.split_whitespace().next()?;
            address.split('%').next()?.parse().ok()
        })
        .collect()
}

/// resolved's global and per-link servers; `None` when resolved is not
/// running (it is never activated just to ask).
pub(crate) async fn from_resolved(connection: &Connection) -> Option<Vec<IpAddr>> {
    if !dbus::name_has_owner(connection, RESOLVED).await {
        return None;
    }
    let servers = dbus::get(connection, RESOLVED, RESOLVED_PATH, RESOLVED_MANAGER, "DNS")
        .await
        .ok()?;
    let mut addresses: Vec<IpAddr> = dbus::structures(&servers)
        .filter_map(server_address)
        .collect();
    addresses.dedup();
    Some(addresses)
}

/// One `(iiay)` entry: interface index, address family, address bytes.
fn server_address(fields: &[Variant<'_>]) -> Option<IpAddr> {
    let [_, Variant::I32(family), address] = fields else {
        return None;
    };
    let bytes = dbus::bytes(address)?;
    match *family {
        FAMILY_INET => <[u8; 4]>::try_from(bytes.as_slice())
            .ok()
            .map(|octets| IpAddr::V4(Ipv4Addr::from(octets))),
        FAMILY_INET6 => <[u8; 16]>::try_from(bytes.as_slice())
            .ok()
            .map(|octets| IpAddr::V6(Ipv6Addr::from(octets))),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_resolv_conf() {
        let text = "# resolv.conf(5) file generated by tailscale
# For more info, see https://tailscale.com/s/resolvconf-overwrite
# DO NOT EDIT THIS FILE BY HAND -- CHANGES WILL BE OVERWRITTEN

nameserver 100.100.100.100
nameserver fd7a:115c:a1e0::53
nameserver fe80::1%wlo1
search tail3fb635.ts.net
";
        let servers = parse_resolv_conf(text);
        assert_eq!(servers.len(), 3);
        assert_eq!(servers[0], IpAddr::V4(Ipv4Addr::new(100, 100, 100, 100)));
        assert!(servers[1].is_ipv6());
        assert_eq!(servers[2].to_string(), "fe80::1");
    }

    #[test]
    fn decodes_resolved_entries() {
        let fields = [
            Variant::I32(3),
            Variant::I32(FAMILY_INET),
            Variant::new(vec![1_u8, 1, 1, 1]),
        ];
        assert_eq!(
            server_address(&fields),
            Some(IpAddr::V4(Ipv4Addr::new(1, 1, 1, 1)))
        );
        let short = [
            Variant::I32(0),
            Variant::I32(FAMILY_INET6),
            Variant::new(vec![0_u8; 4]),
        ];
        assert_eq!(server_address(&short), None);
    }
}
